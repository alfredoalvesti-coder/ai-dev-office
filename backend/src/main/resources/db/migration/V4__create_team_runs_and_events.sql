CREATE TABLE office.team_runs (
    id UUID PRIMARY KEY,
    project_id UUID NOT NULL REFERENCES office.projects(id),
    demand VARCHAR(5000) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    artifact_json TEXT,
    artifact_hash CHAR(64),
    model VARCHAR(120),
    context_version VARCHAR(80) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE,
    error_code VARCHAR(80),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT team_run_status_valid CHECK (status IN ('QUEUED','RUNNING','AWAITING_APPROVAL','APPROVED','REJECTED','FAILED','CANCEL_REQUESTED','CANCELLED','EXPIRED')),
    CONSTRAINT team_run_idempotency_unique UNIQUE(project_id,idempotency_key)
);
CREATE INDEX team_runs_project_created_idx ON office.team_runs(project_id,created_at DESC,id DESC);

CREATE TABLE office.team_steps (
    id UUID PRIMARY KEY,
    run_id UUID NOT NULL REFERENCES office.team_runs(id) ON DELETE CASCADE,
    attempt_number INTEGER NOT NULL,
    step_number INTEGER NOT NULL,
    role VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    artifact_json TEXT,
    error_code VARCHAR(80),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT team_step_role_valid CHECK (role IN ('PROJECT_MANAGER','BUSINESS_ANALYST','ARCHITECT','DEVELOPER','QA','REVIEWER')),
    CONSTRAINT team_step_status_valid CHECK (status IN ('RUNNING','SUCCEEDED','FAILED','CANCELLED','SKIPPED')),
    CONSTRAINT team_step_number_valid CHECK (step_number BETWEEN 1 AND 6),
    CONSTRAINT team_step_unique UNIQUE(run_id,attempt_number,step_number)
);
CREATE INDEX team_steps_run_idx ON office.team_steps(run_id,step_number);

CREATE TABLE office.team_approvals (
    id UUID PRIMARY KEY,
    run_id UUID NOT NULL UNIQUE REFERENCES office.team_runs(id),
    decision VARCHAR(20) NOT NULL,
    artifact_hash CHAR(64) NOT NULL,
    decided_by VARCHAR(120) NOT NULL,
    created_task_ids TEXT NOT NULL,
    decided_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT team_approval_decision_valid CHECK (decision IN ('APPROVED','REJECTED'))
);

CREATE TABLE office.project_events (
    cursor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    project_id UUID NOT NULL REFERENCES office.projects(id) ON DELETE CASCADE,
    execution_id UUID NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    payload_json TEXT NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX project_events_replay_idx ON office.project_events(project_id,cursor);
